// BucketStore is the metadata the bucket handlers run on: the CreateBucket
// write transaction and the accessible-bucket listing. storage.MetadataStore
// implements both; the fake store stands in for it in tests.
type BucketStore interface {
	CreateBucket(ctx context.Context, request storage.BucketCreate) (storage.Bucket, bool, error)
	ListAccessibleBuckets(ctx context.Context, request storage.BucketListRequest) (storage.BucketListPage, error)
}

// Buckets serves the P0 bucket operations of API v2 4.2: CreateBucket,
// HeadBucket and ListBuckets. The router has already authenticated the caller
// and authorized the request on the bucket, so HeadBucket only answers 200;
// CreateBucket re-runs its conditions as a metadata transaction; ListBuckets
// asks the store for the buckets the caller owns or holds a grant on.
type Buckets struct{ Store BucketStore }

// NewBucketHandlers wires the bucket handlers into a Router's Handlers map.
func NewBucketHandlers(store BucketStore) map[Operation]Handler {
	b := &Buckets{Store: store}
	return map[Operation]Handler{CreateBucket: b.CreateBucket, HeadBucket: b.HeadBucket, ListBuckets: b.ListBuckets}
}

// maxBucketConfigBytes bounds the CreateBucketConfiguration body, which names
// one location constraint and nothing else.
const maxBucketConfigBytes = 16 << 10

// createBucketConfiguration is the CreateBucket body (API v2 4.2): an absent
// body means the gateway's own region, exactly like us-east-1 clients.
type createBucketConfiguration struct {
	XMLName            xml.Name `xml:"CreateBucketConfiguration"`
	LocationConstraint string   `xml:"LocationConstraint"`
}

// CreateBucket publishes a new bucket incarnation (API v2 4.2): the owner is
// the creating user, the dedup domain is the owner's default_domain at create
// time and the bucket_id is generated by the transaction, never reused. The
// name follows the S3 rules and reserved patterns; LocationConstraint must be
// absent or equal to the gateway region — a wrong region is an error, not
// something the gateway ignores. The router already answered for a taken name;
// the transaction closes that race the same way, by the existing owner.
func (b *Buckets) CreateBucket(w http.ResponseWriter, r *Request) error {
	if !validBucketName(r.Bucket) {
		return &Error{Code: ErrInvalidBucketName, Bucket: r.Bucket}
	}
	if r.HTTP.ContentLength != 0 {
		var config createBucketConfiguration
		if err := r.Body.DecodeXML(&config, maxBucketConfigBytes); err != nil {
			return err
		}
		if config.LocationConstraint != "" && config.LocationConstraint != r.Region() {
			return &Error{Code: ErrInvalidRequest, Message: fmt.Sprintf("The location constraint '%s' does not match the gateway region '%s'; the request was not ignored.", config.LocationConstraint, r.Region()), Bucket: r.Bucket}
		}
	}
	bucket, created, err := b.Store.CreateBucket(r.HTTP.Context(), storage.BucketCreate{CredentialID: r.Caller.AccessKeyID, UserID: r.Caller.UserID, Name: r.Bucket})
	switch {
	case errors.Is(err, storage.ErrAccessDenied):
		// The credential or user was revoked between the signature and the
		// transaction: the request was authenticated, so this is
		// AccessDenied, not InvalidAccessKeyId (API v2 2.2.3).
		return &Error{Code: ErrAccessDenied}
	case err != nil:
		return fmt.Errorf("s3: create bucket %q: %w", r.Bucket, err)
	case !created:
		if bucket.OwnerID == r.Caller.UserID {
			return &Error{Code: ErrBucketAlreadyOwnedByYou, Bucket: r.Bucket}
		}
		return &Error{Code: ErrBucketAlreadyExists, Bucket: r.Bucket}
	}
	w.Header().Set("Location", "/"+r.Bucket)
	w.WriteHeader(http.StatusOK)
	return nil
}

// HeadBucket answers 200 for a caller the router already authorized with
// read on an existing bucket; 403 and 404 never had a body (API v2 4.2).
func (b *Buckets) HeadBucket(w http.ResponseWriter, r *Request) error {
	w.Header().Set("x-amz-bucket-region", r.Region())
	w.WriteHeader(http.StatusOK)
	return nil
}

// listAllMyBucketsResult is the ListBuckets response of API v2 4.2. Owner.ID
// is the caller's DSG user_id; buckets the caller cannot access are absent,
// so one user's namespace is never listed to another.
type listAllMyBucketsResult struct {
	XMLName xml.Name `xml:"ListAllMyBucketsResult"`
	Owner   struct {
		ID string
	}
	Buckets struct {
		Bucket []bucketSummary `xml:",omitempty"`
	}
}
type bucketSummary struct {
	Name         string
	CreationDate bucketCreationDate
}

// bucketCreationDate formats CreationDate the way S3 clients parse it
// (ISO 8601, UTC).
type bucketCreationDate struct{ storage.Bucket }

func (d bucketCreationDate) MarshalXML(e *xml.Encoder, start xml.StartElement) error {
	if d.CreatedAt.IsZero() {
		return e.EncodeElement("", start)
	}
	return e.EncodeElement(d.CreatedAt.UTC().Format("2006-01-02T15:04:05.000Z"), start)
}

// maxBucketPage is one page of ListBuckets. The S3 operation has no paging
// parameters, so callers see at most this many buckets of their own.
const maxBucketPage = 1000

// ListBuckets returns only the buckets the caller owns or holds a read or
// write grant on (API v2 2.2.1, 4.2): system admin alone lists nothing.
func (b *Buckets) ListBuckets(w http.ResponseWriter, r *Request) error {
	page, err := b.Store.ListAccessibleBuckets(r.HTTP.Context(), storage.BucketListRequest{PrincipalID: r.Caller.UserID, Limit: maxBucketPage})
	if errors.Is(err, storage.ErrAccessDenied) {
		return &Error{Code: ErrAccessDenied}
	}
	if err != nil {
		return fmt.Errorf("s3: list buckets of %s: %w", r.Caller.UserID, err)
	}
	var out listAllMyBucketsResult
	out.Owner.ID = r.Caller.UserID
	out.Buckets.Bucket = make([]bucketSummary, 0, len(page.Buckets))
	for _, bucket := range page.Buckets {
		out.Buckets.Bucket = append(out.Buckets.Bucket, bucketSummary{Name: bucket.Name, CreationDate: bucketCreationDate{bucket}})
	}
	body, err := xml.Marshal(out)
	if err != nil {
		return fmt.Errorf("s3: encode ListBuckets: %w", err)
	}
	body = append([]byte(xml.Header), body...)
	h := w.Header()
	h.Set("Content-Type", "application/xml")
	h.Set("Content-Length", strconv.Itoa(len(body)))
	w.WriteHeader(http.StatusOK)
	if _, err := w.Write(body); err != nil {
		return fmt.Errorf("s3: write ListBuckets: %w", err)
	}
	return nil
}

// validBucketName is the S3 bucket naming of API v2 4.2 (3-63 characters of
// lowercase letters, digits, hyphens and dot-separated labels that begin and
// end with a letter or digit), minus the forms S3 reserves: an IP-address
// shape, the xn-- and sthree- prefixes and the -s3alias/--ol-s3 suffixes.
func validBucketName(name string) bool {
	if len(name) < 3 || len(name) > 63 {
		return false
	}
	for _, label := range splitDot(name) {
		if !bucketLabel(label) {
			return false
		}
	}
	// S3 rejects names shaped like an IP address ("192.168.1.1").
	if _, err := netip.ParseAddr(name); err == nil {
		return false
	}
	for _, reserved := range []string{"xn--", "sthree-"} {
		if len(name) >= len(reserved) && name[:len(reserved)] == reserved {
			return false
		}
	}
	for _, reserved := range []string{"-s3alias", "--ol-s3"} {
		if len(name) >= len(reserved) && name[len(name)-len(reserved):] == reserved {
			return false
		}
	}
	return true
}

// splitDot splits name on '.'; an empty label ("a..b", ".a", "a.") is kept as
// an empty string so bucketLabel rejects it.
func splitDot(name string) []string {
	var out []string
	start := 0
	for i := 0; i < len(name); i++ {
		if name[i] == '.' {
			out = append(out, name[start:i])
			start = i + 1
		}
	}
	return append(out, name[start:])
}

// bucketLabel is one dot-separated label: lowercase letters, digits and
// hyphens, beginning and ending with a letter or digit.
func bucketLabel(label string) bool {
	if label == "" {
		return false
	}
	for i := 0; i < len(label); i++ {
		c := label[i]
		switch {
		case c >= 'a' && c <= 'z', c >= '0' && c <= '9':
		case c == '-':
			if i == 0 || i == len(label)-1 {
				return false
			}
		default:
			return false
		}
	}
	return true
}
